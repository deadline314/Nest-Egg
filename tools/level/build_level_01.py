#!/usr/bin/env python3
"""第一章「雨夜」地圖產生器：以程式擺放地形與實體，輸出 data/levels/level_01_map.json。

地圖檔本身是可直接手改的資料；這個腳本是「設計稿」，方便大幅調整版面後重新產生，
並在輸出前檢查跳躍高度與坑洞寬度是否在角色能力範圍內。
用法：python3 tools/level/build_level_01.py
"""
import json
import os

W, H = 350, 24
GROUND = 20            # 街道地面的列（上緣 y = 320）
TILE = 16
PLAYER_JUMP_TILES = 5  # 玩家跳躍約 88px ≈ 5.5 格
MECH_JUMP_TILES = 3    # 機甲跳躍約 54px ≈ 3.4 格

g = [['.'] * W for _ in range(H)]


def put(x, y, c):
    g[y][x] = c


def fill(x0, x1, y0, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = c


def empty(x, y):
    return g[y][x] == '.'


# ---------------------------------------------------------------------------
# 外框與地面
fill(0, 0, 0, H - 1, '#')
fill(W - 1, W - 1, 0, H - 1, '#')
fill(1, W - 2, GROUND, H - 1, '#')

# ---------------------------------------------------------------------------
# S1 屋頂巷弄（0..69）：從屋頂出發，跨越巷道，再一路往下到街道；衝鋒槍
fill(1, 27, 15, GROUND - 1, '#')          # 屋頂 A（上緣 y=240）
fill(9, 10, 13, 14, '#')                  # 冷氣機
fill(29, 30, 18, GROUND - 1, '#')         # 巷子裡的木箱（掉下去時的踏腳）
fill(32, 52, 15, GROUND - 1, '#')         # 屋頂 B（上緣 y=240）
fill(37, 38, 13, 14, '#')                 # 掩體
# 隱藏房間：屋頂 B 的牆面內側挖出一間小室，入口是巷子裡看得到的裂縫牆（打破才進得去）。
fill(32, 38, 16, GROUND - 1, '.')
put(32, 19, 'x')                          # 裂縫牆（1×4 格，往上長）
put(36, 19, 'v')                          # 老K的語音留言（收集品）
put(37, 19, 'i')                          # 醫療針
put(24, 14, 'f')                          # 天穹宣傳單（收集品）
fill(53, 57, 17, 17, '=')                 # 往下的雨棚
fill(59, 63, 18, 18, '=')
put(3, 14, 'P')
put(5, 14, '1')
put(6, 14, '&')                           # radio_start
put(13, 14, '2')
put(22, 14, 'g')
put(34, 14, '3')
put(44, 14, 'g')
put(42, 14, 'U')                          # 衝鋒槍
put(50, 14, 'i')                          # 醫療針
put(48, 14, 'H')
put(56, 19, '4')
put(62, 19, 'C')
put(66, 19, '~')
for x, y, c in [(29, 16, '$'), (24, 9, '@'), (47, 8, '%'), (60, 12, '$'), (66, 13, '%')]:
    put(x, y, c)

# ---------------------------------------------------------------------------
# S2 霓虹市集（70..159）：雨棚上的保全、頭頂的監視蜂、霰彈槍、鎮暴員
for x0 in (74, 88, 104, 126, 142):
    fill(x0, x0 + 6, 16, 16, '=')
put(78, 15, 'g')
put(84, 19, '&')                          # radio_market
put(92, 19, 'g')
put(96, 19, '5')
put(98, 8, 'd')
put(102, 19, '6')
put(112, 19, 'S')
put(116, 7, 'd')
put(118, 19, '7')
put(119, 19, '&')                         # radio_shield
put(124, 19, 'r')
put(130, 15, 'g')
put(135, 19, 'H')
put(128, 19, 'e')                         # 護盾電池
put(140, 19, 'C')
put(146, 15, 'g')
put(152, 19, 'g')
for x in (86, 120, 145):
    put(x, 19, '~')
for x, y, c in [(72, 11, '$'), (80, 12, '%'), (84, 4, '@'), (95, 11, '$'), (101, 13, '%'), (108, 11, '$'),
                (118, 4, '@'), (122, 12, '$'), (133, 11, '%'), (139, 12, '$'), (150, 4, '@'), (156, 11, '$')]:
    put(x, y, c)

# ---------------------------------------------------------------------------
# S3 貨運站（160..239）：突擊步槍、機甲、貨櫃上的砲台、自爆蟲群、擲彈兵、榴彈發射器
put(162, 19, 'C')
put(165, 19, '&')                         # radio_mech
put(166, 19, 'R')                          # 突擊步槍（上機甲前）
put(168, 19, 'M')
put(171, 19, '8')
fill(178, 183, 17, 19, '#')               # 貨櫃（3 格高）
put(180, 16, 't')
put(182, 16, 'y')                         # 貨運清單（收集品，貨櫃頂）
fill(186, 188, GROUND, H - 1, '.')        # 排水溝（坑）
put(192, 19, 'g')
fill(200, 205, 18, 19, '#')               # 貨櫃（2 格高）
put(202, 17, 't')
put(210, 19, 'g')
put(214, 19, 'r')
fill(218, 223, 17, 19, '#')               # 貨櫃（3 格高）
put(220, 16, 'm')
put(226, 19, '9')
for x in (229, 231, 233):
    put(x, 19, 'b')
put(236, 19, 'H')
put(238, 19, 'G')                          # 榴彈發射器
put(196, 19, 'i')                         # 醫療針
for x, y, c in [(166, 11, '%'), (174, 6, '@'), (196, 12, '$'), (208, 10, '%'), (228, 11, '$')]:
    put(x, y, c)
for x in (176, 207):
    put(x, 19, '~')

# ---------------------------------------------------------------------------
# S4 天穹設施入口（240..309，室內）：雷射柵欄、尖刺、迫擊兵、貫穿光束、電磁軌道砲
fill(240, W - 2, 0, 3, '#')               # 天花板（室內不下雨）
put(242, 19, 'C')
put(245, 19, '&')                         # radio_facility
fill(252, 252, 13, 19, '|')
fill(257, 262, 16, 16, '=')
fill(264, 270, 16, 16, '=')
fill(258, 268, 19, 19, '^')
put(272, 19, 't')
fill(276, 276, 13, 19, '|')
put(280, 19, 'g')
put(282, 19, 'e')                         # 護盾電池
fill(284, 286, 17, 17, '=')               # 上高台的踏板
fill(288, 293, 15, 19, '#')               # 高台
put(290, 14, 'm')
put(296, 19, 'L')
put(300, 19, 'g')
put(302, 19, 'H')
put(304, 19, 'C')
put(306, 19, '&')                         # radio_last
put(308, 19, 'V')                          # 電磁軌道砲（頭目戰前）
put(309, 19, 'i')                         # 醫療針
for x in (250, 262, 270, 282, 290, 300, 322, 332, 340):
    put(x, 4, '*')

# ---------------------------------------------------------------------------
# S5 頭目機庫（310..349）
put(310, 19, 'B')
fill(316, 321, 15, 15, '=')
fill(338, 343, 15, 15, '=')
fill(326, 333, 11, 11, '=')
put(342, 19, 'X')

# 信用點：小堆散在路上（c），隱藏房間裡有一大堆（q）
for x, y in [(17, 14), (47, 14), (100, 19), (114, 19), (138, 19), (175, 19), (195, 19), (212, 19), (225, 19), (274, 19), (298, 19)]:
    if empty(x, y):
        put(x, y, 'c')
put(35, 19, 'q')

# 室外路燈
for x in (12, 28, 40, 62, 76, 96, 110, 130, 150, 172, 190, 210, 230):
    if empty(x, 9):
        put(x, 9, '*')


# ---------------------------------------------------------------------------
# 檢查：沿路面（實心地形；單向平台是選擇性路線不列入）的高度變化不能超過跳躍能力、坑不能太寬
def surface(x):
    for y in range(H):
        if g[y][x] == '#':
            if y < 4 and g[y][x] == '#' and x >= 240:  # 室內天花板
                continue
            return y
    return None


problems = []
prev = surface(1)
gap = 0
for x in range(2, W - 1):
    s = surface(x)
    if s is None or s >= H - 1:
        gap += 1
        continue
    if gap > 3:
        problems.append(f"col {x}: 坑寬 {gap} 格，機甲跳不過")
    gap = 0
    if prev is not None and prev - s > PLAYER_JUMP_TILES:
        problems.append(f"col {x}: 往上 {prev - s} 格，玩家跳不上去")
    prev = s
if problems:
    raise SystemExit("\n".join(problems))

rows = [''.join(r) for r in g]
segments = [[r[i:i + 50] for r in rows] for i in range(0, W, 50)]
path = os.path.join(os.path.dirname(__file__), '..', '..', 'data', 'levels', 'level_01_map.json')
with open(path, 'w') as f:
    f.write('{\n  "segments": [\n')
    for si, seg in enumerate(segments):
        f.write('    [\n' + ',\n'.join('      "' + r + '"' for r in seg) + '\n    ]' + (',' if si < len(segments) - 1 else '') + '\n')
    f.write('  ]\n}\n')
json.load(open(path))
print(f"level_01: {W}x{H} written")
