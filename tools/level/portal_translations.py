def localized_prompt(source: str) -> dict[str, str]:
    """Keep the key token under the game's existing input-binding formatter."""
    if not source.startswith("{interact} "):
        return {}
    copies = PROMPTS.get(source.removeprefix("{interact} "))
    return {"en": "{interact} " + copies[0], "ja": "{interact} " + copies[1]} if copies else {}


def localized_lock(source: str) -> dict[str, str]:
    copies = LOCKS.get(source)
    return {"en": copies[0], "ja": copies[1]} if copies else {}
